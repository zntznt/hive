// Every string in Hive, keyed, in the two languages it is written in.
//
// The app is written in Mexican Spanish and translated into English, so ES is
// the table that has to be complete: `t` falls back to it by construction, and
// a key missing from EN shows Spanish, which is visible and fixable, rather
// than a key name, which looks like a crash.
//
// Three rules, each of which cost a bug to learn.
//
// Whole sentences live here, not fragments. Spanish reorders them ("Le debes
// $9.50 a Rocío"), so a sentence assembled from translated pieces is always
// wrong in one language or the other. Where a sentence has a value in it, it
// is a `{slot}` and `tf` fills it.
//
// Copy is read at render, never at module load. These are plain data; the
// reading happens through `t(lang, key)` or the `useT()` hook, so nothing
// freezes whichever language rendered first.
//
// And the fallback is whole-language: a phone set to Italian gets English, not
// an Italian shell with Spanish rows in it.
//
// Length is the thing to watch. Spanish runs 15 to 25 percent longer than
// English, so English is the easy direction and Spanish is the one that
// overflows. The tab bar is the canary: five labels, fixed width, no wrap.

